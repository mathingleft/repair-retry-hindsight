"""Verify rollouts against a running kimina server (/verify), with the
admit-soundness screen (G1): PASS requires zero errors AND no
"declaration uses 'sorry'" warning (catches `admit` and sorry-axioms).

  python verify_run.py --kimina-url http://localhost:8000
"""
import argparse, json, os, re, sys, time, threading
# Soundness screen. Lean 4.29 emits "declaration uses `sorry`" (backticks); older builds used ASCII quotes.
# The screen committed before 2026-08-29 01:30 PT matched only 'sorry' and therefore NEVER fired on this stack
# (bug found by the user; see HANDOFF). Match any quoting, and `sorry` without quotes.
import re as _re
SORRY_RE = _re.compile(r"declaration uses\s+[`'‘\"]?sorry")
from concurrent.futures import ThreadPoolExecutor
import requests
from lean_extract import extract_lean_code   # pipeline splice: preamble + statement + model body

FENCE = re.compile(r"```(?:lean4?|lean)\n(.*?)```", re.S)

def extract_code(text):
    if not text: return None
    m = FENCE.findall(text)
    if m: return m[-1].strip()
    if "theorem" in text or ":=" in text: return text.strip()
    return None


def verdict(resp_item):
    err = resp_item.get("error")
    if err: return "FAIL", str(err)
    msgs = (resp_item.get("response") or {}).get("messages") or resp_item.get("messages") or []
    errors = [m for m in msgs if m.get("severity") == "error"]
    if errors: return "FAIL", "; ".join((m.get("data") or "")[:200] for m in errors[:5])
    if any(SORRY_RE.search(m.get("data") or "") for m in msgs):
        return "FAIL", "sorryAx (sorry/admit) — soundness screen"
    return "PASS", None

# kimina answers a body timeout as a per-item error, but a REPL that dies mid-proof
# (e.g. a 12GB `interval_cases` blow-up) surfaces as HTTP 500 for the WHOLE batch.
# Header-startup timeouts are load noise, not a verdict on the proof.
TRANSIENT = ("header command timed out",)

def _post(a, codes):
    resp = requests.post(f"{a.kimina_url}/verify", json={
        "codes": codes, "timeout": a.timeout, "infotree_type": None},
        timeout=a.timeout * len(codes) + 120)
    resp.raise_for_status()
    return {x.get("custom_id"): x for x in resp.json().get("results", [])}

def _transient(item):
    return any(t in str(item.get("error") or "") for t in TRANSIENT)

def verify_codes(a, codes, tries=3):
    results = {}
    try:
        results = _post(a, codes)
    except (requests.RequestException, ValueError) as e:
        print(f"  batch of {len(codes)} failed ({str(e)[:120]}); retrying singly", flush=True)
    for c in codes:
        cid = c["custom_id"]
        if cid in results and not _transient(results[cid]): continue
        for t in range(tries):
            try:
                item = _post(a, [c]).get(cid) or {"error": "no result returned"}
            except (requests.RequestException, ValueError) as e:
                item = {"error": f"verifier crash (REPL died / HTTP error): {str(e)[:200]}"}
            results[cid] = item
            if not _transient(item) and "verifier crash" not in str(item.get("error") or ""): break
            time.sleep(10)
    return results

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kimina-url", required=True)
    ap.add_argument("--outdir", default=os.path.join(os.path.dirname(__file__), "out"))
    ap.add_argument("--timeout", type=int, default=120)
    ap.add_argument("--bank", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "bank.jsonl"))
    ap.add_argument("--batch", type=int, default=8)   # unused since the threaded rewrite; kept for CLI compat
    ap.add_argument("--workers", type=int, default=int(os.environ.get("LEAN_SERVER_MAX_REPLS", 8)))
    a = ap.parse_args()
    src = os.path.join(a.outdir, "rollouts.jsonl")
    dst = os.path.join(a.outdir, "verified.jsonl")
    done = set()
    if os.path.exists(dst):
        for l in open(dst):
            d = json.loads(l); done.add((d["id"], d["arm"], d["sample_idx"]))
    rows = []
    for l in open(src):
        if not l.strip(): continue
        try: rows.append(json.loads(l))
        except json.JSONDecodeError: pass      # partial trailing line while the generator is still appending
    # API-error rows are stripped + regenerated by gpu_run.sbatch; never verify them (the final
    # pass is guarded to 0 error rows anyway).
    nerr = sum(str(r.get("finish", "")).startswith("error:") for r in rows)
    if nerr: print(f"skipping {nerr} API-error rows (to be regenerated)")
    rows = [r for r in rows if not str(r.get("finish", "")).startswith("error:")
            and (r["id"], r["arm"], r["sample_idx"]) not in done]
    print(f"{len(rows)} rollouts to verify", flush=True)
    # One proof per request from N worker threads (N = kimina MAX_REPLS): a 120s Lean timeout or a
    # REPL crash then stalls only its own REPL instead of a whole sequential batch.
    lock = threading.Lock()
    stmts = {b["id"]: b["statement"] for b in map(json.loads, open(a.bank)) }
    def work(r):
        cid = f"{r['id']}|{r['arm']}|{r['sample_idx']}"
        if not r["text"]:
            rec = {**r, "text": None, "status": "FAIL", "error": "no code extracted"}
        else:
            c = extract_lean_code(r["text"], stmts[r["id"]])
            res = verify_codes(a, [{"custom_id": cid, "proof": c}])
            st, err = verdict(res.get(cid, {"error": "no result returned"}))
            if st == "FAIL" and "extract_lean_code_no_body_parsed" in c: err = "no proof body parsed; " + (err or "")
            rec = {**r, "text": None, "lean_code": c, "status": st, "error": err}
        with lock:
            with open(dst, "a") as f:
                f.write(json.dumps(rec) + "\n")
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        for i, _ in enumerate(ex.map(work, rows), 1):
            if i % 50 == 0 or i == len(rows): print(f"  {i}/{len(rows)}", flush=True)
    print("done ->", dst)

if __name__ == "__main__":
    main()
